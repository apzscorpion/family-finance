"""Regenerates mobile/lib/v3/phosphor_catalog.dart from the bundled font.

Phosphor.ttf names its icons through ligatures (typing "fork-knife" draws
the fork-and-knife glyph), so the name -> codepoint map is read from the
font's GSUB table. Run after replacing the font:
    .venv/Scripts/python.exe scripts/gen_phosphor_catalog.py
Needs: pip install fonttools
"""
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "mobile" / "assets" / "fonts" / "Phosphor.ttf"
OUT = ROOT / "mobile" / "lib" / "v3" / "phosphor_catalog.dart"


def catalog():
    font = TTFont(FONT)
    cmap = font.getBestCmap()
    glyph_cp = {}
    for cp, glyph in cmap.items():
        glyph_cp.setdefault(glyph, cp)
    letter = {g: chr(cp) for g, cp in glyph_cp.items() if cp < 128}
    out = {}
    for lookup in font["GSUB"].table.LookupList.Lookup:
        for sub in lookup.SubTable:
            sub = getattr(sub, "ExtSubTable", sub)
            for first, ligs in getattr(sub, "ligatures", {}).items():
                for lig in ligs:
                    chars = [letter.get(first)] + [letter.get(c) for c in lig.Component]
                    cp = glyph_cp.get(lig.LigGlyph)
                    if cp and None not in chars:
                        out["".join(chars)] = cp
    return dict(sorted(out.items()))


def main():
    icons = catalog()
    lines = [
        "// GENERATED by scripts/gen_phosphor_catalog.py from",
        "// assets/fonts/Phosphor.ttf. Do not edit by hand.",
        "import 'package:flutter/widgets.dart';",
        "",
        "/// Every icon in the bundled Phosphor font, by its Phosphor name.",
        "const Map<String, IconData> phosphorCatalog = {",
    ]
    lines += [f"  '{n}': IconData(0x{cp:x}, fontFamily: 'Phosphor')," for n, cp in icons.items()]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(icons)} icons -> {OUT}")


if __name__ == "__main__":
    main()
